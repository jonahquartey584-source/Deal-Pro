// netlify/functions/billing-portal.mts
var json = (data, status = 200) => Response.json(data, { status, headers: { "Cache-Control": "no-store" } });
var billing_portal_default = async (request, _context) => {
  const user = await getUser();
  if (!user) return json({ error: "Please sign in." }, 401);
  const state = await getStore({ name: "deal-premium-accounts", consistency: "strong" }).get(`users/${user.id}/state`, { type: "json" });
  const customer = state?.stripe?.customer;
  if (!customer) return json({ error: "no_subscription" }, 404);
  if (!process.env.STRIPE_SECRET_KEY) return json({ error: "portal_unavailable" }, 503);
  const res = await fetch("https://api.stripe.com/v1/billing_portal/sessions", {
    method: "POST",
    headers: { Authorization: `Bearer ${process.env.STRIPE_SECRET_KEY}`, "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ customer, return_url: new URL("/?billing=1", request.url).toString() }).toString()
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok || !data.url) {
    console.error("Billing portal failed", data?.error?.message);
    return json({ error: "portal_unavailable" }, 502);
  }
  return json({ url: data.url });
};
var config = { path: "/api/billing-portal", method: "POST" };
export {
  config,
  billing_portal_default as default
};
